

function setup()
{
	can.setFilter(0x600,0x700,0);
}

function gotCANFrame(bus,id,len,data)
{
	host.log("GotCan");
	if(id==0x6F1) 
	{
		if((data[0] == 0x12)&&((data[1]&0xF0)==0x30))
		{
			host.log("FC received");
			can.sendFrame(0,0x612,8,[0xF1, 0x21, 0x00, 0x00, 0x31, 0x6E, 0x00, 0x58 ]);
			can.sendFrame(0,0x612,8,[0xF1, 0x22, 0x66, 0x66, 0x29, 0xFF, 0xFF, 0xFF ]);
		}
		if((data[0] == 0x12)&&((data[1]&0xF0)==0x10))
		{
			host.log("FF received");
			can.sendFrame(0,0x612,8,[0xF1, 0x30, 0x00, 0x00, 0xFF, 0xFF, 0xFF, 0xFF ]);
		}
	}
}