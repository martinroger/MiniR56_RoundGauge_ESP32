
 var DDLISet = false;

function setup()
{
	can.setFilter(0x600,0x700,0);
}

function gotCANFrame(bus,id,len,data)
{
	//host.log("GotCan");
	if(id==0x6F1 && data[0] == 0x12) 
	{
		if((data[1]&0xF0)==0x10)
		{
			//host.log("FF received");
			can.sendFrame(0,0x612,8,[0xF1, 0x30, 0x00, 0x00, 0xFF, 0xFF, 0xFF, 0xFF ]);
		}
		if((data[1]&0xF0)==0x30)
		{
			//host.log("FC received");
			can.sendFrame(0,0x612,8,[0xF1, 0x21, 0x02, 0xFF, 0x31, 0x6E, 0x55, 0x58 ]);
			can.sendFrame(0,0x612,8,[0xF1, 0x22, 0x70, 0x66, 0x67, 0xFF, 0xFF, 0xFF ]);
		}
		if((data[1])==0x29)
		{
			//host.log("End of DDLI setup");
			can.sendFrame(0,0x612,8,[0xF1,0x02,0x6C,0xF0,0xFF,0xFF,0xFF,0xFF]);
		}
		if(((data[1]&0xF0)==0x00) && (data[2]==0x21) && (data[3]==0xF0) )
		{
			///host.log("Read request");
			can.sendFrame(0,0x612,8,[0xF1,0x10,0x0E,0x61,0xF0,0xBB,0x03,0x8A]);
		}
		if( ((data[1]&0xF0)==0x00) && (data[2]==0x2C) && (data[3]==0xF0) && (data[4]==0x04))
		{
			//host.log("Clear request");
			can.sendFrame(0,0x612,8,[0xF1,0x02,0x6C,0xF0,0xFF,0xFF,0xFF,0xFF]);
		}
		
	}
}